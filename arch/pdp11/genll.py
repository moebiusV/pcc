#!/usr/bin/env python3
"""
genll.py -- build llhelpers.h from ll.c.

    genll.py [pcc]        (default: ~/claude/pcc/install/bin/pcc)

Compiles ll.c with `pcc -O -xdmr -S`, splits the assembly into one block per
helper, renames the compiler's numbered labels so that blocks cannot collide with
a file's own, and records which helpers each one calls.  The order of NAMES is
the order of the LL_* numbers in lowerll.c (plus the two internal helpers).
"""
import os, re, subprocess, sys

NAMES = ['cpy', 'add', 'sub', 'mul', 'dvs', 'dvu', 'mds', 'mdu', 'and', 'or', 'xor',
         'shl', 'shr', 'ush', 'neg', 'com', 'cmp', 'ucm', 'fls', 'flu', 'tol',
         'm32', 'udm', 'ulr']
CNAME = {n: '__ll' + n for n in NAMES}

here = os.path.dirname(os.path.abspath(__file__))
pcc = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/claude/pcc/install/bin/pcc')
out = subprocess.run([pcc, '-O', '-xdmr', '-S', '-o', '-', os.path.join(here, 'll.c')],
                     capture_output=True, text=True, check=True).stdout
blocks = {}
cur = None
for line in out.split('\n'):
    m = re.match(r'^(__ll\w+):', line)
    if m:
        cur = m.group(1)
        blocks[cur] = []
    if cur is None:
        continue
    if line.startswith('.globl') or line.startswith('.text') or line.startswith('.data') or line.startswith('~') or line == '':
        continue
    blocks[cur].append(line)

texts = []
deps = []
for i, n in enumerate(NAMES):
    lines = blocks[CNAME[n]]
    body = '\n'.join(lines)
    labs = sorted(set(re.findall(r'\bL(\d+)\b', body)), key=int)
    tag = 'h%c%c' % (chr(97 + i // 26), chr(97 + i % 26))
    for k, l in enumerate(labs):
        body = re.sub(r'\bL%s\b' % l, '%s%d' % (tag, k), body)
    called = set(re.findall(r'__ll\w+', body)) - {CNAME[n]}
    mask = 0
    for c in called:
        for j, m2 in enumerate(NAMES):
            if CNAME[m2] == c:
                mask |= 1 << j
    texts.append(body + '\n')
    deps.append(mask)

with open(os.path.join(here, 'llhelpers.h'), 'w') as f:
    f.write('/* Generated by genll.py from ll.c: the long long helpers of the pdp11 backend,\n'
            ' * one block of assembly each, written into a file that needs them (lowerll.c).\n'
            ' * C calling convention; the operands are addresses. */\n')
    f.write('#define NLLH %d\n' % len(NAMES))
    f.write('static const char *const llh_text[NLLH] = {\n')
    for t in texts:
        f.write('\t"' + t.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\n', '\\n"\n\t"') + '",\n')
    f.write('};\nstatic const int llh_deps[NLLH] = {\n')
    for m in deps:
        f.write('\t0x%x,\n' % m)
    f.write('};\n')
print('llhelpers.h: %d helpers, %d bytes of assembly' % (len(NAMES), sum(len(t) for t in texts)))
